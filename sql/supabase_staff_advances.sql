-- Staff salary advances and scheduled payroll recovery.
begin;

alter table public.payroll
  add column if not exists advance_id bigint;

create table if not exists public.staff_salary_advances (
  id bigint generated by default as identity primary key,
  staff_id text not null,
  staff_name text not null,
  principal numeric not null check (principal > 0),
  monthly_deduction numeric not null check (monthly_deduction > 0),
  effective_month text not null check (effective_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  disbursed_date date not null default current_date,
  disbursement_account text not null check (disbursement_account in ('cash', 'bank')),
  voucher_id text not null,
  notes text,
  created_at timestamptz not null default now()
);
alter table public.staff_salary_advances
  add column if not exists disbursed_date date not null default current_date,
  add column if not exists disbursement_account text not null default 'cash'
    check (disbursement_account in ('cash', 'bank')),
  add column if not exists voucher_id text;
create unique index if not exists staff_salary_advances_voucher_id_uidx
  on public.staff_salary_advances (voucher_id)
  where voucher_id is not null;

alter table public.payroll
  drop constraint if exists payroll_advance_id_fkey;
alter table public.payroll
  add constraint payroll_advance_id_fkey
  foreign key (advance_id) references public.staff_salary_advances(id) on delete restrict;

alter table public.staff_salary_advances enable row level security;
revoke all on table public.staff_salary_advances from public, anon;
grant select, insert on table public.staff_salary_advances to authenticated;
grant update, delete on table public.staff_salary_advances to authenticated;

drop policy if exists staff_salary_advances_select on public.staff_salary_advances;
drop policy if exists staff_salary_advances_insert on public.staff_salary_advances;
drop policy if exists staff_salary_advances_update on public.staff_salary_advances;
drop policy if exists staff_salary_advances_delete on public.staff_salary_advances;
create policy staff_salary_advances_select on public.staff_salary_advances
  for select to authenticated using (
    public.app_has_page_permission('staff', 'v')
    or public.app_has_page_permission('accounts', 'v')
  );
create policy staff_salary_advances_insert on public.staff_salary_advances
  for insert to authenticated with check (public.app_has_page_permission('staff', 'a') or public.app_has_page_permission('staff', 'e'));
create policy staff_salary_advances_update on public.staff_salary_advances
  for update to authenticated using (public.app_has_page_permission('staff', 'e'))
  with check (public.app_has_page_permission('staff', 'e'));
create policy staff_salary_advances_delete on public.staff_salary_advances
  for delete to authenticated using (public.app_has_page_permission('staff', 'd') or public.app_has_page_permission('staff', 'e'));

drop policy if exists staff_salary_advance_accounts_select on public.accounts;
drop policy if exists staff_salary_advance_accounts_insert on public.accounts;
drop policy if exists staff_salary_advance_accounts_update on public.accounts;
drop policy if exists staff_salary_advance_accounts_delete on public.accounts;
create policy staff_salary_advance_accounts_select on public.accounts
  for select to authenticated using (
    (public.app_has_page_permission('staff', 'v') or public.app_has_page_permission('accounts', 'v'))
    and voucher_id like 'ADV-%'
    and to_account = 'Staff Salary Advance'
  );
create policy staff_salary_advance_accounts_insert on public.accounts
  for insert to authenticated with check (
    (public.app_has_page_permission('staff', 'a') or public.app_has_page_permission('staff', 'e'))
    and voucher_id like 'ADV-%'
    and to_account = 'Staff Salary Advance'
    and from_account in ('cash', 'bank')
    and amount_in = 0
    and amount_out > 0
    and public.app_can_change_day(date)
  );
create policy staff_salary_advance_accounts_update on public.accounts
  for update to authenticated using (
    public.app_has_page_permission('staff', 'e')
    and voucher_id like 'ADV-%'
    and to_account = 'Staff Salary Advance'
  ) with check (
    public.app_has_page_permission('staff', 'e')
    and voucher_id like 'ADV-%'
    and to_account = 'Staff Salary Advance'
    and from_account in ('cash', 'bank')
    and amount_in = 0
    and amount_out > 0
    and public.app_can_change_day(date)
  );
create policy staff_salary_advance_accounts_delete on public.accounts
  for delete to authenticated using (
    (public.app_has_page_permission('staff', 'e') or public.app_has_page_permission('accounts', 'd') or public.app_has_page_permission('accounts', 'e'))
    and voucher_id like 'ADV-%'
    and to_account = 'Staff Salary Advance'
    and public.app_can_change_day(date)
  );

create or replace view public.staff_advance_payroll_recoveries as
  select advance_id, coalesce(sum(advance), 0) as recovered_amount, count(*) as recovery_count
  from public.payroll
  where advance_id is not null
    and (public.app_has_page_permission('accounts', 'v') or public.app_has_page_permission('staff', 'v'))
  group by advance_id;
revoke all on public.staff_advance_payroll_recoveries from public, anon;
grant select on public.staff_advance_payroll_recoveries to authenticated;

grant usage, select on sequence public.staff_salary_advances_id_seq to authenticated;

create or replace function public.lite_record_staff_salary_advance(
  p_staff_id text,
  p_principal numeric,
  p_monthly_deduction numeric,
  p_effective_month text,
  p_disbursed_date date,
  p_account text,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_staff public.staff%rowtype;
  v_voucher text;
  v_advance_id bigint;
  v_attempt integer;
begin
  if not (public.app_has_page_permission('staff', 'a') or public.app_has_page_permission('staff', 'e')) then
    raise exception 'Staff Add or Edit permission is required to record a salary advance.'
      using errcode = '42501';
  end if;
  if p_principal is null or p_principal <= 0 or round(p_principal, 2) <> p_principal
     or p_monthly_deduction is null or p_monthly_deduction <= 0
     or round(p_monthly_deduction, 2) <> p_monthly_deduction
     or p_monthly_deduction > p_principal then
    raise exception 'Advance and monthly recovery must be positive amounts with at most two decimal places; recovery cannot exceed the advance.'
      using errcode = '22023';
  end if;
  if p_effective_month is null or p_effective_month !~ '^[0-9]{4}-(0[1-9]|1[0-2])$'
     or p_disbursed_date is null
     or p_effective_month < to_char(p_disbursed_date, 'YYYY-MM') then
    raise exception 'Choose a valid effective month that is not before the disbursement date.'
      using errcode = '22023';
  end if;
  if lower(coalesce(p_account, '')) not in ('cash', 'bank') then
    raise exception 'Choose Cash or Bank as the disbursement account.' using errcode = '22023';
  end if;
  if not public.app_can_change_day(p_disbursed_date) then
    raise exception 'This disbursement date is closed or unavailable for changes.'
      using errcode = '42501';
  end if;
  select * into v_staff
  from public.staff
  where staff_id = p_staff_id and lower(coalesce(status, 'Active')) = 'active'
  for share;
  if not found then
    raise exception 'The selected staff member is unavailable or inactive.' using errcode = 'P0002';
  end if;

  for v_attempt in 1..10 loop
    v_voucher := 'ADV-' || floor(100000 + random() * 900000)::text;
    exit when not exists (select 1 from public.accounts where voucher_id = v_voucher)
      and not exists (select 1 from public.staff_salary_advances where voucher_id = v_voucher);
  end loop;
  if exists (select 1 from public.accounts where voucher_id = v_voucher)
     or exists (select 1 from public.staff_salary_advances where voucher_id = v_voucher) then
    raise exception 'Could not allocate a unique advance voucher number. Please retry.';
  end if;

  insert into public.accounts (
    voucher_id, from_account, to_account, description,
    amount_in, amount_out, date, remarks
  ) values (
    v_voucher, lower(p_account), 'Staff Salary Advance',
    'Staff salary advance: ' || coalesce(nullif(btrim(v_staff.staff_name), ''), v_staff.staff_id),
    0, p_principal, p_disbursed_date, nullif(btrim(coalesce(p_notes, '')), '')
  );
  insert into public.staff_salary_advances (
    staff_id, staff_name, principal, monthly_deduction, effective_month,
    disbursed_date, disbursement_account, voucher_id, notes
  ) values (
    v_staff.staff_id, v_staff.staff_name, p_principal, p_monthly_deduction,
    p_effective_month, p_disbursed_date, lower(p_account), v_voucher,
    nullif(btrim(coalesce(p_notes, '')), '')
  ) returning id into v_advance_id;

  return jsonb_build_object('advance_id', v_advance_id, 'voucher_id', v_voucher);
end;
$$;
revoke all on function public.lite_record_staff_salary_advance(text, numeric, numeric, text, date, text, text) from public, anon;
grant execute on function public.lite_record_staff_salary_advance(text, numeric, numeric, text, date, text, text) to authenticated;

notify pgrst, 'reload schema';
commit;
